export const EXAM_DOMAINS = [
  'Threats, Attacks & Vulnerabilities',
  'Technologies & Tools',
  'Architecture & Design',
  'Identity & Access Management',
  'Risk Management',
  'Cryptography & PKI',
] as const;

export type ExamDomain = (typeof EXAM_DOMAINS)[number];

export function getQuestionsByDomain(domain: string): ExamQuestion[] {
  return EXAM_QUESTIONS.filter((q) => q.domain === domain);
}

export function sampleQuestions(count: number, seed?: number): ExamQuestion[] {
  const shuffled = [...EXAM_QUESTIONS];
  // Fisher-Yates with optional deterministic seed for review reproducibility
  let s = seed ?? Date.now();
  for (let i = shuffled.length - 1; i > 0; i--) {
    s = (s * 1664525 + 1013904223) & 0xffffffff;
    const j = Math.abs(s) % (i + 1);
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
